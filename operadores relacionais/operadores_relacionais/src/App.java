public class App {
    public static void main(String[] args) throws Exception {
        System.out.println("True and False?");
        int num1, num2;
        num1 = 100;
        num2 = 10;
        /* > Maior que
          < Menor que 
          != Diferente de
          == A estrutura e o tipo são iguais? Exemplo: 100 == 100? true!
          
          OBS: A saida sempre retorna verdadeiro ou false (True/False)
          */
        System.out.println(num1 > num2);
        System.out.println(num1 < num2);
        System.out.println(num1 != num2);
        System.out.println(num1 >= num2);
        System.out.println(num1 <= num2);
        System.out.println(num1 == num2);
        
    }
}
